"""生成合成网格快捷按钮的图标（14x14）。

用法：python scripts/gen_icons.py
输出：src/main/resources/assets/fieldcrafting/textures/gui/tweak_*.png
"""

import os

from PIL import Image

ICONS = {
    "rotate": """
..............
.....####.....
...##....##...
..#........#.#
..#.........##
.#.........###
.#............
.#............
.#............
..#........#..
..#........#..
...##....##...
.....####.....
..............
""",
    "balance": """
..............
..............
..##..##..##..
..##..##..##..
..............
..............
..##..##..##..
..##..##..##..
..............
..............
..##..##..##..
..##..##..##..
..............
..............
""",
    "to_player": """
..............
.....####.....
.....####.....
.....####.....
.....####.....
.....####.....
..##########..
...########...
....######....
.....####.....
......##......
..............
.############.
..............
""",
    "to_field": """
..............
..............
.....#........
....##........
...###........
..###########.
.############.
.############.
..###########.
...###........
....##........
.....#........
..............
..............
""",
}
INK = (245, 245, 245, 255)
SHADOW = (40, 40, 40, 255)
SIZE = 14
OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..",
    "src",
    "main",
    "resources",
    "assets",
    "fieldcrafting",
    "textures",
    "gui",
)


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, art in ICONS.items():
        rows = art.strip("\n").split("\n")
        img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == "#" and x + 1 < SIZE and y + 1 < SIZE:
                    img.putpixel((x + 1, y + 1), SHADOW)
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == "#":
                    img.putpixel((x, y), INK)
        img.save(os.path.join(OUT, "tweak_%s.png" % name))
    print("生成完成：%s" % os.path.normpath(OUT))


if __name__ == "__main__":
    main()
